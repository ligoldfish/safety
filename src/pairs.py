DEFAULT_PAIR = "qwen35_9b_to_08b"

# Tokens of the canonical pair, longest-first, so replacement never corrupts a
# longer token (e.g. "qwen35_9b" must not be replaced inside "qwen35_9b_to_08b").
_CANON = PAIRS[DEFAULT_PAIR]


def replacement_pairs(pair_id: str) -> List[tuple[str, str]]:
    """Ordered (old, new) string replacements that re-target a canonical config
    (yaml text or a filename) to ``pair_id``. Longest-first to avoid collisions."""
    p = PAIRS[pair_id]
    return [
        ("qwen35_9b_to_08b", p["pair_id"]),       # pair_id (must be first: superstring)
        ("Qwen3.5-0.8B", p["student"]["name"]),    # model names before short tags
        ("Qwen3.5-9B", p["teacher"]["name"]),
        ("qwen35_08b", p["student"]["tag"]),       # short tags last
        ("qwen35_9b", p["teacher"]["tag"]),
    ]


def apply_tokens(text: str, pair_id: str) -> str:
    for old, new in replacement_pairs(pair_id):
        text = text.replace(old, new)
    return text


def is_template(pair_id: str) -> bool:
    return bool(PAIRS.get(pair_id, {}).get("is_template"))


def list_generated_pairs() -> List[str]:
    """Pairs the generator should emit configs for (all except the template)."""
    return [pid for pid in PAIRS if not is_template(pid)]
