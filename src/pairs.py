"""Teacher->student model-pair registry for the cross-scale safety-transfer experiments.

Single source of truth for the model pairs the pipeline runs on. The original
experiment is Qwen3.5-9B -> Qwen3.5-0.8B; this registry adds the cross-family /
cross-scale extension pairs (Llama-3.x and Qwen3).

How it is used
--------------
* scripts/gen_pair_configs.py renders every per-pair config by loading the
  canonical ``qwen35_9b_to_08b`` template yamls and STRING-REPLACING the model
  identifier tokens below (teacher/student name + tag + the pair_id), then
  setting ``lora.target_modules`` to the pair's architecture-correct list.
  Because output_root / model.path / cross-config references all embed those
  same tokens, one set of replacements re-targets an entire config.
* scripts/15_run_oneclick.py resolves config paths by substituting the same
  tokens into the canonical filenames (``--pair`` arg; default reproduces the
  existing Qwen3.5 filenames byte-for-byte -> fully backward compatible).

Replacement tokens (applied longest-first to avoid partial collisions):
    "qwen35_9b_to_08b" -> pair_id
    "Qwen3.5-9B"       -> teacher.name      "qwen35_9b"  -> teacher.tag
    "Qwen3.5-0.8B"     -> student.name      "qwen35_08b" -> student.tag

NOTE: hyperparameters (top_k / lambda / energy / epochs, incl. the WJB/WGM
per-baseline overrides in 15_run_oneclick.py) are REUSED across pairs by design
(user decision 2026-06-24); only model identity + LoRA target modules change.
"""
